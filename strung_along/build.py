import base64, hashlib, pathlib, re, sys
# Builds chord-grid.html from src/chordgrid.src.html. Edit the source, never the built file: the build overwrites it.
# The built file carries a hash of itself, so a build refuses to run over hand edits (pass --force to discard them).
root = pathlib.Path(__file__).parent
out = root/'chord-grid.html'
STAMP = re.compile(r'<!-- GENERATED by build.py from src/chordgrid.src.html: edit that file, not this one. sha256:([0-9a-f]{64}) -->')
sha = lambda s: hashlib.sha256(s.encode()).hexdigest()

if out.exists() and '--force' not in sys.argv:
    old = out.read_text(); m = STAMP.search(old)
    if m and sha(STAMP.sub('', old, 1)) != m.group(1):
        sys.exit('chord-grid.html was edited by hand since the last build, and building now would erase those edits.\n'
                 'Move them into src/chordgrid.src.html first (git diff chord-grid.html shows them), or run with --force to discard them.')

font = base64.b64encode((root/'fonts/DepartureMono-Regular.otf').read_bytes()).decode()
src = (root/'src/chordgrid.src.html').read_text().replace('__FONT__', font)
head = '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"></head><body>'
html = head + src + '</body></html>'
stamp = STAMP.pattern.replace(r'([0-9a-f]{64})', sha(html)).replace('\\', '')
out.write_text(html.replace('<!doctype html>', '<!doctype html>' + stamp, 1))
