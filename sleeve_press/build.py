import base64, hashlib, json, pathlib, re, shutil, sys
import shaders
# Builds ../sleeve-press/index.html from src/sleeve.src.html and src/engine.js. Edit the sources, never the built file:
# the build overwrites it. Every Haecceity shader is ported from the app at build time (shaders.py) and must compile
# in the browser (test/shaders.cjs). The built file carries a hash of itself, so a build refuses to run over hand
# edits (pass --force to discard them).
root = pathlib.Path(__file__).parent
site = root.parent / 'sleeve-press'
out = site / 'index.html'
STAMP = re.compile(r'<!-- GENERATED by sleeve_press/build.py from sleeve_press/src: edit those files, not this one. sha256:([0-9a-f]{64}) -->')
sha = lambda s: hashlib.sha256(s.encode()).hexdigest()

if out.exists() and '--force' not in sys.argv:
    old = out.read_text(); m = STAMP.search(old)
    if m and sha(STAMP.sub('', old, 1)) != m.group(1):
        sys.exit('sleeve-press/index.html was edited by hand since the last build, and building now would erase those edits.\n'
                 'Move them into sleeve_press/src first (git diff sleeve-press/index.html shows them), or run with --force to discard them.')

ported = shaders.build()
expected = sum(len(list(shaders.APP.glob(p))) for _, p in shaders.GROUPS)
if len(ported) != expected or len(ported) < 141:
    sys.exit(f'Only {len(ported)} of {expected} Haecceity shaders were ported.')
data = json.dumps(ported, separators=(',', ':'))
assert '</script' not in data
font = base64.b64encode((root/'fonts/DepartureMono-Regular.otf').read_bytes()).decode()
engine = (root/'src/engine.js').read_text()
src = (root/'src/sleeve.src.html').read_text().replace('__ENGINE__', engine).replace('__SHADERS__', data).replace('__FONT__', font)
head = '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"></head><body>'
html = head + src + '</body></html>'
site.mkdir(exist_ok=True)
(site/'fonts').mkdir(exist_ok=True)
for f in (root/'fonts').glob('*.woff2'): shutil.copy2(f, site/'fonts'/f.name)
shutil.copytree(root/'fonts/licenses', site/'fonts/licenses', dirs_exist_ok=True)
stamp = STAMP.pattern.replace(r'([0-9a-f]{64})', sha(html)).replace('\\', '')
out.write_text(html.replace('<!doctype html>', '<!doctype html>' + stamp, 1))
print(f'{len(ported)} shaders ported; wrote {out.relative_to(root.parent)} ({out.stat().st_size // 1024} KB) and {len(list((site/"fonts").glob("*.woff2")))} fonts')
